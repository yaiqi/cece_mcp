"""Entity MCP 面向 Agent 的中文业务状态返回合同。"""


def _响应(状态码: str, 摘要: str, **fields: object) -> dict:
    return {"状态码": 状态码, "摘要": 摘要, **fields}


def 唯一匹配(实体类型: str, 检索关键字: str, 标准实体: dict) -> dict:
    return _响应("唯一匹配", f"已唯一识别{实体类型}主体。", 检索关键字=检索关键字, 标准实体=标准实体)


def 多候选(实体类型: str, 检索关键字: str, 候选列表: list[dict]) -> dict:
    return _响应("多候选", f"命中多个{实体类型}主体，无法自动确定，请用户确认。", 检索关键字=检索关键字, 候选列表=候选列表)


def 未匹配(实体类型: str, 检索关键字: str) -> dict:
    return _响应("未匹配", f"未匹配到{实体类型}主体，请检查关键词后重试。", 检索关键字=检索关键字, 候选列表=[])


def 实体未匹配(实体类型: str, 原始输入: str) -> dict:
    return _响应("实体未匹配", f"未匹配到{实体类型}主体，请调用对应实体消歧工具获取候选。", 原始输入=原始输入)


def 查询成功(数据: object) -> dict:
    return _响应("查询成功", "查询成功。", 数据=数据)


def 查询无数据(摘要: str) -> dict:
    return _响应("查询无数据", 摘要, 数据=[])


def 调用失败(摘要: str) -> dict:
    return _响应("调用失败", 摘要)
